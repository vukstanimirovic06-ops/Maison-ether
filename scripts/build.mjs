/**
 * Build step for MAISON ÉTHER.
 *
 * 1. Bundles js/app.js and its modules into js/bundle.js as one classic
 *    (non-module) script. Module scripts are fetched with CORS, so they fail in
 *    sandboxed previews (opaque "null" origin) and from file://. A classic
 *    script loads everywhere.
 * 2. Pre-renders the home page into index.html, so the hero and every section
 *    are in the HTML before any script runs.
 *
 * Usage: npm run build   (run after editing anything in js/)
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tmpdir } from 'node:os';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (p) => path.join(root, p);

await build({
  entryPoints: [r('js/app.js')],
  outfile: r('js/bundle.js'),
  bundle: true,
  format: 'iife',
  target: ['es2019'],
  minify: true,
  legalComments: 'none',
  banner: { js: '/* MAISON ÉTHER — generated by scripts/build.mjs from js/*.js. Do not edit. */' },
});

// Render the home view with the same templates the app uses.
const tmp = mkdtempSync(path.join(tmpdir(), 'me-build-'));
const ssr = path.join(tmp, 'home.mjs');
await build({
  stdin: { contents: "export { home } from './js/views.js';", resolveDir: root },
  outfile: ssr,
  bundle: true,
  format: 'esm',
  platform: 'node',
});
const { home } = await import(pathToFileURL(ssr).href);
rmSync(tmp, { recursive: true, force: true });

const START = '<!--prerender:start-->';
const END = '<!--prerender:end-->';
const index = readFileSync(r('index.html'), 'utf8');
const a = index.indexOf(START);
const b = index.indexOf(END);
if (a < 0 || b < a) throw new Error('index.html is missing the prerender markers');
writeFileSync(r('index.html'), index.slice(0, a + START.length) + home() + index.slice(b));

console.log('Built js/bundle.js and pre-rendered the home page into index.html');
